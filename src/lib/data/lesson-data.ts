// Lesson content structure for LSM learning app
export type ExerciseType = "multiple-choice" | "video-match" | "sign-recognition"

export interface Exercise {
  id: string
  type: ExerciseType
  question: string
  videoUrl?: string // Enlace al video de la seña (ahora en formato de incrustación)
  options: string[]
  correctAnswer: string
  xpReward: number
}

export interface Lesson {
  id: string
  topicId: string
  lessonNumber: number
  title: string
  description: string
  exercises: Exercise[]
  totalXp: number
}

export interface Topic {
  id: string
  title: string
  description: string
  icon: string
  order: number
  lessons: Lesson[]
}

